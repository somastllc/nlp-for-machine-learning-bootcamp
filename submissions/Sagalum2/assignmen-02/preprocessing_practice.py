def to_wn_pos(treebank_tag):
    if treebank_tag.startswith("J"):
        return "a"
    if treebank_tag.startswith("V"):
        return "v"
    if treebank_tag.startswith("R"):
        return "r"
    return "n"


def pipeline(text, stop_set, name):
    print(f"\n--- Pipeline: {name} ---")
    print("0. original", text)
    s1 = text.lower()
    print("1. lowercase", s1)
    s2 = re.sub(r"[^a-z'\s]", " ", s1)          # keep letters, apostrophes, spaces
    s2 = re.sub(r"\s+", " ", s2).strip()
    print("2. regex clean", s2)
    s3 = word_tokenize(s2)
    print("3. tokenize", s3)
    s4 = [t for t in s3 if t not in stop_set]
    print("4. stopword removal", s4)
    s5 = [lemmatizer.lemmatize(w, to_wn_pos(tag)) for w, tag in pos_tag(s4)]
    print("5. lemmatize", s5)
    neg = [t for t in s5 if t in KEEP]
    print("Negation words surviving", neg)
    return s5


