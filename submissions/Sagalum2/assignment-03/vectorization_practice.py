def sorted_vocab(vectorizer):
    """Vocabulary as a list of (term, column index), sorted by column index."""
    return sorted(vectorizer.vocabulary_.items(), key=lambda kv: kv[1])


def print_vocab(vectorizer, label):
    terms = [t for t, _ in sorted_vocab(vectorizer)]
    print(f"{label} (size {len(terms)}):")
    print("  ", terms)


def print_matrix(matrix, row_names, col_names, decimals=None):
    """Print a dense matrix with row and column labels."""
    arr = np.asarray(matrix)
    if decimals is not None:
        arr = np.round(arr, decimals)
    width = max(max(len(c) for c in col_names), max(len(str(v)) for v in arr.ravel())) + 2
    row_w = max(len(r) for r in row_names) + 2
    print(" " * row_w + "".join(c.rjust(width) for c in col_names))
    for name, row in zip(row_names, arr):
        cells = "".join(str(v).rjust(width) for v in row)
        print(name.ljust(row_w) + cells)

