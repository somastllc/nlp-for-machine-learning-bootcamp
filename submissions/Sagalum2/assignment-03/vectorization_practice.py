def one_hot(word, vocab):
    """Return a list of 0s with a single 1 at the word's position."""
    vector = [0] * len(vocab)
    if word in vocab:
        vector[vocab.index(word)] = 1
    return vector


print("\nOne-hot vectors for the sentence 'free cash':")
for w in "free cash".split():
    print(f"  {w:6s} -> {one_hot(w, one_hot_vocab)}")

print("\nOne-hot vectors for the sentence 'win free cash':")
sentence = "win free cash".split()
for w in sentence:
    print(f"  {w:6s} -> {one_hot(w, one_hot_vocab)}")
print(f"\nNumber of vectors for 'free cash'     : {len('free cash'.split())}")
print(f"Number of vectors for 'win free cash' : {len(sentence)}")
print("Answer: each word gets its own vector, so the number of vectors equals")
print("the number of words. The result is a (words x 6) table whose height")
print("changes with sentence length, so it is not a fixed-size description of")
print("the document. Words outside the vocabulary would become all-zero vectors.")

