# Task 8: TF-IDF by hand for D2

heading("Task 8: TF-IDF by hand for D2 (textbook formula)")

N = len(docs)
d2_tokens = analyzer(docs[1])
total_d2 = len(d2_tokens)
print("D2 tokens (as the vectorizer sees them):", d2_tokens)
print("Total tokens in D2:", total_d2)
print("Number of documents N:", N)

by_hand = {}
for word in ["cash", "today"]:
    count = d2_tokens.count(word)
    df = int(doc_freq[feature_names.index(word)])
    tf = count / total_d2
    idf = math.log(N / df)
    tfidf = tf * idf
    by_hand[word] = tfidf
    print(f"\nWord '{word}':")
    print(f"  count in D2         = {count}")
    print(f"  TF = count / total  = {count}/{total_d2} = {tf:.4f}")
    print(f"  df                  = {df}")
    print(f"  IDF = ln(N/df)      = ln({N}/{df}) = {idf:.4f}")
    print(f"  TF-IDF = TF x IDF   = {tfidf:.4f}")

sk = X_tfidf.toarray()[1]
sk_cash = sk[tfidf_names.index("cash")]
sk_today = sk[tfidf_names.index("today")]
print(f"\nscikit-learn weights in D2: cash = {sk_cash:.4f}, today = {sk_today:.4f}")
print("Textbook ranking     :", "cash > today" if by_hand["cash"] > by_hand["today"] else "today >= cash")
print("scikit-learn ranking :", "cash > today" if sk_cash > sk_today else "today >= cash")
print("Same ranking?", (by_hand["cash"] > by_hand["today"]) == (sk_cash > sk_today))
print("Note: the numbers differ because scikit-learn uses smoothed IDF "
      "ln((1+N)/(1+df)) + 1 and L2 normalisation, but the ordering agrees.")

